/*
 * Les ≈ 25 prestataires de démo, en Île-de-France.
 * Format compact et lisible : buildSeed.ts le transforme en vraies entités
 * (User, ProviderProfile, Offering, Media…) et calcule les champs dérivés
 * (prix « à partir de », note moyenne) avec les règles de common/rules.
 */

export interface SeedOffering {
  title: string;
  categoryId: string;
  pricingType: PricingType;
  /** En euros pour rester lisible ici ; converti en centimes par buildSeed. */
  priceEuros?: number;
  description?: string;
  durationMinutes?: number;
  minGuests?: number;
  maxGuests?: number;
  isActive?: boolean;
}

export interface SeedProvider {
  slug: string;
  displayName: string;
  owner: { firstName: string; lastName: string };
  city: string;
  postalCode: string;
  location: { lat: number; lng: number };
  categoryIds: string[];
  culturalOriginIds: string[];
  languages: string[];
  legalType: LegalType;
  siret?: string;
  isProVerified: boolean;
  cancellationPolicy: CancellationPolicy;
  maxBookingsPerDay?: number;
  travelRadiusKm: number;
  responseTimeHours?: number;
  status?: ProviderStatus;
  rejectionReason?: string;
  bio: string;
  offerings: SeedOffering[];
  /** Notes des avis passés (une réservation terminée + un avis par note). */
  pastRatings: number[];
  /** Nombre de photos dans la galerie (6 par défaut). */
  photoCount?: number;
}

